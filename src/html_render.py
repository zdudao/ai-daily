def save_entity_report(
    entries: List[Dict],
    config: Dict,
    date_str: str,
    data_dir: str = "news-data",
) -> str:
    """生成并保存实体洞察日报 HTML 到 data_dir/daily-{date}.html。

    Returns:
        生成的 HTML 文件路径
    """
    from pathlib import Path

    html_page = render_entity_report(entries, config, date_str)
    path = Path(data_dir) / f"daily-{date_str}.html"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html_page, encoding="utf-8")
    print(f"📊 实体洞察日报已生成: {path}")
    return str(path)
