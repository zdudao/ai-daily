def md_to_html_page(
    title: str, md_body: str, footer_note: str = ""
) -> str:
    """把 markdown 正文渲染为完整 HTML 页面。

    Args:
        title: 页面标题（放入 <title> 和页头）
        md_body: markdown 正文（不含 frontmatter）
        footer_note: 页头副标题/日期等说明文字
    """
    body_html = markdown.markdown(
        md_body,
        extensions=["extra", "tables", "fenced_code", "sane_lists"],
    )
    # markdown 输出的段落已带缩进,统一规范化缩进
    body_html = "\n".join(line.strip() for line in body_html.splitlines())
    return _build_page(title, body_html, footer_note)


def generate_html_file(md_filepath: str, title: str, footer_note: str = "") -> str:
    """读取 .md 文件（自动剥离 YAML frontmatter），生成同名 .html 文件。

    Args:
        md_filepath: markdown 文件路径（.md）
        title: 页面标题
        footer_note: 页头副标题

    Returns:
        生成的 .html 文件路径；md 不存在或为空时返回空字符串。
    """
    from pathlib import Path

    from src.markdown_utils import parse_frontmatter

    md_path = Path(md_filepath)
    if not md_path.exists():
        return ""

    text = md_path.read_text(encoding="utf-8")
    _, body = parse_frontmatter(text)
    if not body.strip():
        return ""

    html_path = md_path.with_suffix(".html")
    html_page = md_to_html_page(title, body, footer_note)
    html_path.write_text(html_page, encoding="utf-8")
    return str(html_path)


