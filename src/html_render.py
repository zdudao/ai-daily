def _deduce_card_html(d: Dict) -> str:
    """渲染顾问行动卡片（motive/industry_impact/feasibility/ecosystem + card 判断/决策/备忘录）"""
    def esc(v):
        return html.escape(str(v)) if v else ""

    # 兼容中英文键名变体
    def get(dd, *keys, default=""):
        for k in keys:
            v = dd.get(k)
            if v:
                return v
        return default

    card = d.get("card") or {}
    if not isinstance(card, dict):
        card = {}

    motive = esc(get(d, "motive", "动机分析"))
    ecosystem = esc(get(d, "ecosystem", "生态位冲击"))

    # 影响行业排序（兼容列表/字符串、中英文字段）
    impacts = d.get("industry_impact") or d.get("impact") or []
    impact_html = ""
    if isinstance(impacts, list) and impacts:
        parts = []
        for i, m in enumerate(impacts, 1):
            if not isinstance(m, dict):
                continue
            ind = get(m, "industry", "name", "行业")
            reason = get(m, "reason", "note", "说明", "理由")
            parts.append(
                f'<div class="d-map-item"><b>{i}. {esc(ind)}</b>'
                f"<div>{esc(reason)}</div></div>"
            )
        if parts:
            impact_html = "\n".join(parts)
    elif impacts:
        impact_html = f"<p>{esc(impacts)}</p>"

    # 落地可行性研判（四维度）
    feas = d.get("feasibility") or d.get("feasible") or {}
    feas_html = ""
    if isinstance(feas, dict):
        rows = [
            ("💰 成本门槛", get(feas, "cost", "cost_gate", "成本门槛", "成本")),
            ("🧑 消费习惯匹配度", get(feas, "habit", "消费习惯", "习惯")),
            ("🏗️ 基础设施依赖", get(feas, "infrastructure", "基础设施")),
            ("⚖️ 政策与平台风险", get(feas, "policy", "政策风险", "风险")),
        ]
        parts = [f"<p><b>{t}</b>：{esc(v)}</p>" for t, v in rows if v]
        if parts:
            feas_html = "\n".join(parts)

    judgement = esc(get(card, "judgement", "一句话核心判断", "核心判断"))
    decision = esc(
        get(card, "decision", "对老板的一句话决策建议", "一句话决策建议", "summary", "开封话总结", "决策建议")
    )
    memo = esc(get(card, "memo", "顾问备忘录", "备忘录", "总结"))

    def step(title, body):
        return (
            f'<div class="d-step"><div class="d-step-title">{title}</div>'
            f"{body}</div>"
            if body
            else ""
        )

    return f"""
<details class="deduce">
<summary>📇 顾问行动卡片<span class="d-arrow">▼</span></summary>
<div class="d-body">
  {step("🕵️ 动机分析", f"<p>{motive}</p>")}
  {step("📊 影响行业排序", impact_html)}
  {step("🔧 落地可行性研判", feas_html)}
  {step("⚔️ 生态位冲击", f"<p>{ecosystem}</p>")}
  {step("🎯 一句话核心判断", f"<p>{judgement}</p>")}
  {step("🗣️ 一句话决策建议", f"<p>{decision}</p>")}
  <div class="d-kaifeng">📝 顾问备忘录：{memo}</div>
</div>
</details>
"""


